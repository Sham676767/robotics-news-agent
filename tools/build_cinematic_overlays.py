"""Generate original, seamless procedural effects; no third-party media or licenses."""
from pathlib import Path
import argparse
import math
import random
import subprocess

from PIL import Image, ImageDraw, ImageFilter


def build(root: Path, ffmpeg: str = 'ffmpeg') -> None:
    rng = random.Random(593)
    particles = [(rng.random(), rng.random(), rng.uniform(.4,1.5)) for _ in range(45)]
    for kind, size in [('dust_loop',(270,480)),('fire_loop',(160,160))]:
        folder = root/kind;folder.mkdir(parents=True,exist_ok=True)
        command=[ffmpeg,'-v','error','-y','-f','rawvideo','-pix_fmt','rgb24','-s',f'{size[0]}x{size[1]}','-r','30','-i','-',
                 '-an','-c:v','libx264','-preset','veryfast','-crf','16','-pix_fmt','yuv420p',str(folder/'loop.mp4')]
        process=subprocess.Popen(command,stdin=subprocess.PIPE)
        for frame in range(90):
            phase=2*math.pi*frame/90
            image=Image.new('RGB',size)
            draw=ImageDraw.Draw(image)
            if kind=='dust_loop':
                for x,y,r in particles:
                    px=(x+.012*math.sin(phase+x*5))*size[0]
                    py=(y+.015*math.cos(phase+y*8))*size[1]
                    draw.ellipse((px-r,py-r,px+r,py+r),fill=(44,38,28))
                image=image.filter(ImageFilter.GaussianBlur(.7))
            else:
                for i in range(10):
                    x=25+i*12+5*math.sin(phase+i)
                    h=45+20*math.sin(phase*2+i*.6)
                    draw.ellipse((x-12,150-h,x+12,165),fill=(80,32,4))
                image=image.filter(ImageFilter.GaussianBlur(8))
            process.stdin.write(image.tobytes())
        process.stdin.close()
        if process.wait():raise RuntimeError('Overlay encode failed')
    mask=Image.new('L',(160,160));draw=ImageDraw.Draw(mask)
    draw.ellipse((8,15,152,156),fill=255)
    mask.filter(ImageFilter.GaussianBlur(12)).save(root/'fire_loop/mask.png')
    (root/'LICENSE.txt').write_text('Original procedural effects generated by tools/build_cinematic_overlays.py. CC0-1.0. No third-party footage.\n')


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,default=Path('assets/overlays'))
    args=parser.parse_args();build(args.output)
